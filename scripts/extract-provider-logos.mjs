/**
 * Extracts the five provider brand marks from simple-icons into a small
 * source file.
 *
 * WHY EXTRACT RATHER THAN DEPEND: simple-icons ships about three thousand
 * icons. We need five, on one screen, and a runtime dependency for that is
 * either a large bundle or a tree-shaking bet that has to keep paying off.
 * Five path strings in a checked-in file cost nothing and cannot regress.
 *
 * LICENCE: simple-icons is CC0-1.0 — public domain, no attribution required,
 * which is why this source and not a web search. The BRANDS themselves are
 * still trademarks: these marks identify which platform each card connects
 * to, which is nominative use, and they are not used to suggest any of those
 * companies endorses RepGet.
 *
 *   npm install --no-save simple-icons@16
 *   node scripts/extract-provider-logos.mjs
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import * as icons from "simple-icons";

/** Provider id -> simple-icons export. */
const WANTED = {
  wordpress: "siWordpress",
  ghost: "siGhost",
  shopify: "siShopify",
  webflow: "siWebflow",
  wix: "siWix",
};

const entries = Object.entries(WANTED).map(([id, key]) => {
  const icon = icons[key];
  if (!icon) throw new Error(`simple-icons has no ${key}`);
  return { id, title: icon.title, hex: icon.hex, path: icon.path };
});

const file = `/**
 * Brand marks for the publishing providers.
 *
 * GENERATED by scripts/extract-provider-logos.mjs from simple-icons
 * (CC0-1.0, public domain). Re-run it rather than editing by hand.
 *
 * Five paths rather than a dependency on the whole icon set: we need exactly
 * these, on one screen, and three thousand icons behind a tree-shaking
 * assumption is a worse trade than a file that cannot regress.
 *
 * The brands are trademarks of their owners. They appear here to identify
 * which platform each card connects to — nominative use — and not to imply
 * that any of those companies endorses this product.
 */

export type ProviderLogo = {
  /** Matches the provider id in lib/publishing/registry.ts. */
  id: string;
  title: string;
  /** Official brand colour, without the leading #. */
  hex: string;
  /** SVG path data, drawn in a 24x24 viewBox. */
  path: string;
};

export const PROVIDER_LOGOS: Record<string, ProviderLogo> = {
${entries
  .map(
    (e) => `  ${e.id}: {
    id: ${JSON.stringify(e.id)},
    title: ${JSON.stringify(e.title)},
    hex: ${JSON.stringify(e.hex)},
    path: ${JSON.stringify(e.path)},
  },`,
  )
  .join("\n")}
};
`;

const out = join(process.cwd(), "src", "lib", "publishing", "logos.ts");
writeFileSync(out, file);
console.log(`${entries.length} logos -> src/lib/publishing/logos.ts`);
for (const e of entries) console.log(`  ${e.id.padEnd(10)} #${e.hex}`);
